#!/usr/bin/env python3
"""Regenerates fd_bam_webpki_roots.c from a webpki-roots crate.

jito-solana's registry fetch (reqwest, rustls-tls) trusts exactly
webpki_roots::TLS_SERVER_ROOTS.  Pass the src/lib.rs of the version
pinned in jito-solana's Cargo.lock:

  curl -sL https://static.crates.io/crates/webpki-roots/webpki-roots-1.0.10.crate | tar xz
  ./gen_webpki_roots.py webpki-roots-1.0.10/src/lib.rs 1.0.10 > fd_bam_webpki_roots.c
"""

import re
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(f"usage: {sys.argv[0]} <webpki-roots/src/lib.rs> <version>")
    src = open(sys.argv[1]).read()
    version = sys.argv[2]

    roots = []
    for block in re.findall(r"/\*(.*?)\*/\s*TrustAnchor", src, re.S):
        lines = [l.strip().lstrip("*").strip() for l in block.splitlines()]
        label = next(l for l in lines if l.startswith("Label:"))[6:].strip().strip('"')
        pem = lines[lines.index("-----BEGIN CERTIFICATE-----"):lines.index("-----END CERTIFICATE-----") + 1]
        roots.append((label, pem))

    if len(roots) != src.count("TrustAnchor {"):
        sys.exit("every TrustAnchor must carry its PEM comment")
    # One literal per root keeps each under C's 4095-byte limit (-Wpedantic).
    for label, pem in roots:
        if sum(len(l) + 1 for l in pem) > 4095:
            sys.exit(f"{label}: PEM longer than 4095 bytes")

    out = sys.stdout
    out.write(f"/* Generated by gen_webpki_roots.py from webpki-roots {version}.  Do not edit. */\n\n")
    out.write('#include "fd_bam_webpki_roots.h"\n\n')
    out.write("char const * const fd_bam_webpki_roots[] = {\n")
    for label, pem in roots:
        out.write(f"  /* {label} */\n")
        for i, l in enumerate(pem):
            out.write(f'  "{l}\\n"' + ("," if i == len(pem) - 1 else "") + "\n")
    out.write("};\n\n")
    out.write(f"ulong const fd_bam_webpki_roots_cnt = {len(roots)}UL;\n")
    out.write(f'char const fd_bam_webpki_roots_ver[] = "{version}";\n')

if __name__ == "__main__":
    main()
